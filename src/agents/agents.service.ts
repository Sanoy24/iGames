    /**
     * Earnings the agent has actually EARNED (as opposed to what's been settled/paid
     * out to them  see AgentSettlement). "Game commission" is the referral
     * commission credited via `agent_receipt` ledger entries whose `sourceType`
     * is one of `REFERRAL_COMMISSION_SOURCE_TYPES`  a % of that game's stake
     * (or, for Bingo/Crash, stake × house-edge%) generated by players the agent
     * referred, across every game that pays commission (Bingo, Keno, Crash,
     * Pool, Werk). There is no separate room-owner commission (removed
     * `bingo_room_commission` is no longer written by anything; any pre-existing
     * such entries are historical and excluded from this summary). Withdrawal
     * fees are tracked separately. The
     * `payout_custody` withdrawal credit (reimbursing cash the agent already paid
     * out) is deliberately excluded  it isn't earnings. `deposit_commission` is
     * also excluded  it's a defunct source no longer written anywhere.
     * `period.start`/`period.end` restrict to a window (e.g. today, this month, or
     * a settlement's covered range); omit both for lifetime-to-date.
     */
    async computeAgentEarnings(
        agentId: string,
        period?: { start?: Date; end?: Date },
    ): Promise<{
        referralCommissionMinor: number;
        referralCommissionCount: number;
        gameCommissionMinor: number;
        withdrawalFeesMinor: number;
        totalEarningsMinor: number;
    }> {
        const params: unknown[] = [agentId];
        let dateClause = '';
        if (period?.start) {
            dateClause += ' AND createdAt >= ?';
            params.push(period.start);
        }
        if (period?.end) {
            dateClause += ' AND createdAt < ?';
            params.push(period.end);
        }

        const [row] = await this.systemConfigRepository.query(
            `SELECT
         COALESCE(SUM(CASE WHEN sourceType IN (${REFERRAL_COMMISSION_SOURCE_TYPES_SQL}) THEN amountMinor ELSE 0 END), 0) referralCommission,
         COUNT(CASE WHEN sourceType IN (${REFERRAL_COMMISSION_SOURCE_TYPES_SQL}) THEN 1 END) referralCommissionCount,
         COALESCE(SUM(CASE WHEN sourceType = 'withdrawal' AND JSON_UNQUOTE(JSON_EXTRACT(metadata, '$.kind')) = 'withdrawal_fee' THEN amountMinor ELSE 0 END), 0) withdrawalFees
       FROM ledger_entries
       WHERE userId = ? AND entryType = 'agent_receipt' AND direction = 'credit'${dateClause}`,
            params,
        );

        const referralCommissionMinor = Number(row?.referralCommission ?? 0);
        const referralCommissionCount = Number(
            row?.referralCommissionCount ?? 0,
        );
        const withdrawalFeesMinor = Number(row?.withdrawalFees ?? 0);
        const gameCommissionMinor = referralCommissionMinor;
        return {
            referralCommissionMinor,
            referralCommissionCount,
            gameCommissionMinor,
            withdrawalFeesMinor,
            totalEarningsMinor: gameCommissionMinor + withdrawalFeesMinor,
        };
    }

