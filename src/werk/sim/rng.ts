/**
 * Deterministic PRNG (mulberry32). Identical output in Node and the browser, so
 * a game seed reproduces the exact same maze, coins, and bot play on the
 * authoritative server and the display client alike.
 */
export function makeRng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
