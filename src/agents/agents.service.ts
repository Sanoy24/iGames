type SettlementBlockReason =
    | 'pending_exists'
    | 'cooldown'
    | 'nothing_to_settle'
    | null;

/** All ledger `sourceType`s that represent referral commission, across every game that pays it. */
export const REFERRAL_COMMISSION_SOURCE_TYPES = [
    'bingo_referral_commission',
    'keno_referral_commission',
    'crash_referral_commission',
    'pool_referral_commission',
    'werk_referral_commission',
];
const REFERRAL_COMMISSION_SOURCE_TYPES_SQL = REFERRAL_COMMISSION_SOURCE_TYPES.map(
    (t) => `'${t}'`,
).join(', ');

